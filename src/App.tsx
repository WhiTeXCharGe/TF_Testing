// A link generated by "Start Session"/"Join Session" lands here
// (?session=<id>&role=edit|view) — opened by anyone on the network, in a
// plain browser, no login/build required.
function getSessionParamsFromUrl(): { sessionId: string; role: SessionRole } | null {
  const params = new URLSearchParams(window.location.search);
  const sessionId = params.get('session');
  if (!sessionId) return null;
  return { sessionId, role: params.get('role') === 'view' ? 'view' : 'edit' };
}

// The full editing UI. Its hooks (global shortcuts incl. Ctrl+S/Ctrl+O, the
// constraint checker, the SchedulerWeb incoming-transfer listener) only ever
// mount for a participant who is actually allowed to edit — a view-role
// participant gets ViewPage instead, so none of them run.
function EditorShell() {
  useKeyboardShortcuts();
  useConstraintCheck();
  useIncomingGanttTransfer();
  return (
    <>
      <GanttPage />
      <TaskAddDialog />
      <NewScheduleDialog />
      <ConstraintResultDialog />
      <SendToSchedulerDialog />
      <SessionDialog />
      <ErrorDialog />
    </>
  );
}

// The ONE place read-only rendering is decided, so it can't drift per
// entry point. Read-only is a property of the joined session's role, not of
// how the session was joined: both the URL path (?session=...&role=view, via
// SessionJoinGate) and the in-app SessionDialog's "閲覧のみ" join end up here
// with state.session.role === 'view' and get the same read-only ViewPage.
// Solo mode (no session) and edit-role sessions render the editor as before.
// Exported for App.test.tsx, which drives this decision directly.
export function AppContent() {
  const { state } = useAppContext();
  return state.session?.role === 'view' ? <ViewPage /> : <EditorShell />;
}

function SessionJoinGate({ sessionId, role }: { sessionId: string; role: SessionRole }) {
  const { joinCollabSession, state } = useAppContext();
  const [name, setName] = useState('');
  const [joining, setJoining] = useState(false);
  const [error, setError] = useState<string | null>(null);
  // Tracks whether THIS join attempt has ever reached 'connected'. Only a
  // 'disconnected' seen before that point means the join itself failed (bad
  // id, unreachable server, sync-init {ok:false}) — a 'disconnected' seen
  // afterward is just a live session's connection blipping, which the
  // per-page status indicators (ViewPage's status bar, MenuBar's participant
  // count) already surface without tearing down the editor/viewer underneath.
  const hasConnectedOnceRef = useRef(false);

  useEffect(() => {
    if (!joining) return;
    hasConnectedOnceRef.current = false;
    let cancelled = false;
    joinCollabSession(sessionId, name, role).catch(err => {
      if (!cancelled) setError(err instanceof Error ? err.message : UI.joinSessionErrorFallback);
    });
    return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [joining]);

  // joinCollabSession's promise resolves as soon as the join request is sent —
  // it doesn't wait for the server's actual sync-init reply. A bad/expired
  // session id, or a connection that drops before it ever reaches 'connected',
  // only ever shows up asynchronously as connectionStatus flipping to
  // 'disconnected' (see collabService.ts's handleSyncInit/handleDisconnect).
  // SET_SESSION always seeds state.session with connectionStatus: 'connecting'
  // before this effect can run, so seeing 'disconnected' while joining is true
  // and the session has never yet connected can only mean a real failed join —
  // never an initial idle state. Once connected at least once, a later
  // 'disconnected' (a transient blip, or the host ending the session) is left
  // to the normal in-page UI rather than replacing it with a fatal screen.
  useEffect(() => {
    if (!joining) return;
    const status = state.session?.connectionStatus;
    if (status === 'connected') {
      hasConnectedOnceRef.current = true;
      return;
    }
    if (status === 'disconnected' && !hasConnectedOnceRef.current) {
      setError(UI.joinSessionErrorFallback);
    }
  }, [joining, state.session?.connectionStatus]);

  if (error) {
    return (
      <div style={{ height: '100vh', display: 'flex', alignItems: 'center', justifyContent: 'center', fontFamily: 'MS Gothic, monospace', color: '#c62828' }}>
        {error}
      </div>
    );
  }

  if (!joining) {
    return (
      <div style={{ height: '100vh', display: 'flex', alignItems: 'center', justifyContent: 'center', fontFamily: 'MS Gothic, monospace' }}>
        <form
          onSubmit={e => { e.preventDefault(); if (name.trim()) setJoining(true); }}
          style={{ display: 'flex', flexDirection: 'column', gap: 12, width: 280 }}
        >
          <div style={{ fontSize: 14, fontWeight: 'bold' }}>{UI.joinSessionPromptTitle}</div>
          <input
            autoFocus
            value={name}
            onChange={e => setName(e.target.value)}
            placeholder={UI.joinSessionNamePlaceholder}
            style={{ padding: '6px 8px', fontSize: 13, border: '1px solid #ccc', borderRadius: 4 }}
          />
          <button
            type="submit"
            disabled={!name.trim()}
            style={{ padding: '6px 12px', backgroundColor: '#1976d2', color: '#fff', border: 'none', borderRadius: 4, cursor: name.trim() ? 'pointer' : 'default' }}
          >
            {UI.joinSessionSubmitBtn}
          </button>
        </form>
      </div>
    );
  }

  // No role branch here: joinCollabSession has already seeded state.session
  // with this join's role, and AppContent makes the one read-only decision for
  // every entry point. (SET_SESSION is dispatched synchronously by the effect
  // above, so this resolves on the render right after `joining` flips.)
  return <AppContent />;
}

export default function App() {
  const sessionParams = getSessionParamsFromUrl();
  return (
    <AppProvider>
      {sessionParams
        ? <SessionJoinGate sessionId={sessionParams.sessionId} role={sessionParams.role} />
        : <AppContent />}
    </AppProvider>
  );
}
