import { AppProvider } from './context/AppContext';
import { GanttPage } from './pages/GanttPage';
import { ViewPage } from './pages/ViewPage';
import { ErrorDialog } from './components/Dialogs/ErrorDialog';
import { TaskAddDialog } from './components/Dialogs/TaskAddDialog';
import { NewScheduleDialog } from './components/Dialogs/NewScheduleDialog';
import { ConstraintResultDialog } from './components/Dialogs/ConstraintResultDialog';
import { SendToSchedulerDialog } from './components/Dialogs/SendToSchedulerDialog';
import { ShareViewDialog } from './components/Dialogs/ShareViewDialog';
import { useKeyboardShortcuts } from './hooks/useKeyboardShortcuts';
import { useConstraintCheck } from './hooks/useConstraintCheck';
import { useIncomingGanttTransfer } from './hooks/useIncomingGanttTransfer';
import { useHostBroadcast } from './hooks/useHostBroadcast';

// A link generated by "Live View" sharing lands here (?view=1) — opened by
// anyone on the network, in a plain browser, no login/build required.
function isViewMode(): boolean {
  return new URLSearchParams(window.location.search).get('view') === '1';
}

function AppContent() {
  useKeyboardShortcuts();
  useConstraintCheck();
  useIncomingGanttTransfer();
  useHostBroadcast();
  return (
    <>
      <GanttPage />
      <TaskAddDialog />
      <NewScheduleDialog />
      <ConstraintResultDialog />
      <SendToSchedulerDialog />
      <ShareViewDialog />
      <ErrorDialog />
    </>
  );
}

export default function App() {
  const viewMode = isViewMode();
  return (
    <AppProvider>
      {viewMode ? <ViewPage /> : <AppContent />}
    </AppProvider>
  );
}